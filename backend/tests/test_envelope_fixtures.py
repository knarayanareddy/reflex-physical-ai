"""Every rule in the taxonomy, twice: fires on the trigger, stays quiet just below it.

The fixture corpus in ``data/fixtures/snapshots`` is generated by
``scripts/make_fixtures.py`` from one shared baseline with a single mutation per case, so a
failure here points at exactly one rule.

The test asserts three things per fixture:

1. the expected outcome/rule/mode (the specification);
2. the decision validates against ``$defs/EnvelopeDecision`` (the contract);
3. every rule in the taxonomy appears in the trace of every decision — nothing is silently
   skipped, so a rule that fails to run is distinguishable from a rule that passes.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from app.contracts import validate_payload
from app.envelope import evaluate, load_ruleset

FIXTURES = Path(__file__).resolve().parents[2] / "data" / "fixtures" / "snapshots"
CASES = sorted(FIXTURES.glob("*.json"))


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def test_fixture_corpus_is_complete():
    """A missing case would silently reduce coverage to nine rules."""
    assert len(CASES) == 20, f"expected 10 veto + 10 pass cases, found {len(CASES)}"
    ids = {case.stem for case in CASES}
    for number in range(1, 11):
        assert f"veto_v{number}" in ids or any(i.startswith(f"veto_v{number}_") for i in ids), number
        assert f"pass_v{number}" in ids or any(i.startswith(f"pass_v{number}_") for i in ids), number


@pytest.mark.parametrize("path", CASES, ids=[case.stem for case in CASES])
def test_fixture_matches_the_implementation(path: Path):
    case = _load(path)
    ruleset = load_ruleset()

    # The inputs are themselves contracts, and must validate before they are evaluated.
    validate_payload("SensorSnapshot", case["snapshot"])
    validate_payload("ActionProposal", case["proposal"])

    decision = evaluate(ruleset, case["snapshot"], case["proposal"], case["requested_mode"])

    expect = case["expect"]
    assert decision["outcome"] == expect["outcome"], case["description"]
    assert decision["rule_id"] == expect.get("rule_id"), case["description"]
    if "mode" in expect:
        assert decision["mode"] == expect["mode"], case["description"]
    if "parameter_set" in expect:
        used = {entry["parameter_set_used"] for entry in decision["rule_trace"]}
        assert used == {expect["parameter_set"]}
    if "clamp_velocity" in expect:
        assert decision["clamp_applied"]["velocity"] == expect["clamp_velocity"]
    if "clamp_x" in expect:
        assert decision["clamp_applied"]["target_pose"]["after"]["x"] == expect["clamp_x"]

    # The output is a contract too.
    validate_payload("EnvelopeDecision", decision)


@pytest.mark.parametrize("path", CASES, ids=[case.stem for case in CASES])
def test_every_rule_is_traced_and_traced_once(path: Path):
    case = _load(path)
    ruleset = load_ruleset()
    decision = evaluate(ruleset, case["snapshot"], case["proposal"], case["requested_mode"])

    traced = [entry["rule_id"] for entry in decision["rule_trace"]]
    assert len(traced) == len(set(traced)), f"duplicate trace entries: {traced}"
    assert set(traced) == {rule.rule_id for rule in ruleset.rules}, "a rule was silently skipped"
    assert decision["rule_trace"], "an empty trace is not an audit trail"


@pytest.mark.parametrize("path", CASES, ids=[case.stem for case in CASES])
def test_every_decision_carries_its_own_evidence(path: Path):
    """Self-contained records: snapshot, caller, timestamp, hash and version."""
    case = _load(path)
    ruleset = load_ruleset()
    decision = evaluate(ruleset, case["snapshot"], case["proposal"], case["requested_mode"])

    digest = decision["determinism_hash"]
    assert len(digest) == 64 and all(char in "0123456789abcdef" for char in digest), digest
    assert decision["decision_id"] == "d_" + digest[:24], "decision_id is content-addressed"
    assert decision["envelope_version"].startswith("sha256:")
    # The decision timestamp is the snapshot's, never a process clock: replay must be exact.
    assert decision["decided_at"] == case["snapshot"]["ts_wall"]
    assert decision["mode"] in {"normal", "degraded", "simulation"}
    assert decision["parameter_set"] in {"normal", "degraded"}

    # Every decision is self-contained: the state that justified it travels with it.
    assert decision["sensor_snapshot_inline"] == case["snapshot"]

    flagged = [entry for entry in decision["rule_trace"] if entry["result"] != "PASS"]
    if decision["outcome"] == "VETO":
        assert flagged, "a VETO with nothing flagged cannot be audited"
        # first_veto_index indexes the full trace, not the flagged subset.
        assert decision["rule_id"] == decision["rule_trace"][decision["first_veto_index"]]["rule_id"]
    else:
        if decision["outcome"] == "ALLOW_CLAMPED":
            assert decision["rule_id"] == flagged[0]["rule_id"]
            assert flagged[0]["result"] == "CLAMP"
        else:
            # An unchanged verdict may still be flagged by a degradation, which by design does
            # not stop motion. Nothing else may be flagged without changing the outcome.
            assert decision["rule_id"] is None
            assert all(entry["result"] == "DEGRADE" for entry in flagged), flagged


def test_veto_records_keep_the_refused_plan_verbatim():
    """Insight #2: the record of a refusal has to contain what was refused."""
    case = _load(FIXTURES / "veto_v9_malformed.json")
    decision = evaluate(load_ruleset(), case["snapshot"], case["proposal"], case["requested_mode"])
    assert decision["intended_action"] == case["proposal"]
    assert decision["outcome"] == "VETO"


def test_malformed_proposal_is_vetoed_not_crashed():
    """A payload that cannot even be typed is still a decision, not a 500."""
    snapshot = _load(FIXTURES / "pass_v1_estop.json")["snapshot"]
    decision = evaluate(load_ruleset(), snapshot, {"proposal_id": 7}, "normal")
    validate_payload("EnvelopeDecision", decision)
    assert decision["outcome"] == "VETO"
    assert decision["rule_id"] == "V9_PLAN_MALFORMED"
    assert decision["intended_action"] is None
    assert decision["intended_action_raw"] == {"proposal_id": 7}


def test_measurement_required():
    """If a fixture claims a measured profile it would stop asserting simulation mode."""
    ruleset = load_ruleset()
    assert ruleset.is_measured is False
    assert ruleset.provenance == "synthetic"
